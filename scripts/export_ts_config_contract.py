"""Export Python config DTO shapes/defaults for the independent TS decoder.

This is a development-time bridge, not a runtime Python dependency.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import get_args
from unittest.mock import patch

from pydantic import AliasChoices, BaseModel
from pydantic_core import PydanticUndefined

from nanobot.config.schema import Config
from nanobot.providers.registry import PROVIDERS

OUTPUT = Path(__file__).resolve().parents[1] / "packages/runtime-ts/src/config/contract.json"


def value_json(value):
    if isinstance(value, BaseModel):
        return {field.alias or name: value_json(getattr(value, name))
                for name, field in type(value).model_fields.items()}
    if isinstance(value, dict):
        return {key: value_json(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [value_json(item) for item in value]
    return value


def contract():
    schema = Config.model_json_schema()
    models = {Config}

    def collect(annotation):
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            if annotation not in models:
                models.add(annotation)
                for field in annotation.model_fields.values():
                    collect(field.annotation)
        for arg in get_args(annotation):
            collect(arg)

    for field in Config.model_fields.values():
        collect(field.annotation)
    for model in models:
        node = schema if model is Config else schema["$defs"][model.__name__]
        node["x-model"] = model.__name__
        node["x-extra"] = model.model_config.get("extra", "ignore")
        for name, field in model.model_fields.items():
            aliases = field.validation_alias
            aliases = aliases.choices if isinstance(aliases, AliasChoices) else [aliases or name]
            property_schema = node["properties"][aliases[0]]
            property_schema["x-aliases"] = list(dict.fromkeys([*aliases, name]))
            if model is Config:
                property_schema["x-env-names"] = list(aliases) if field.validation_alias else [f"NANOBOT_{name}"]
            property_schema["x-output"] = field.serialization_alias or field.alias or name
            property_schema["x-exclude"] = bool(field.exclude)
            property_schema["x-omit-null"] = bool(field.exclude_if and field.exclude_if(None))
            property_schema["x-strict"] = any(getattr(item, "strict", False) for item in field.metadata)
            if name == "codex_fast_mode":
                for branch in property_schema.get("anyOf", []):
                    if branch.get("type") == "boolean":
                        branch["x-strict"] = True
            default = field.get_default(call_default_factory=True)
            if default is not PydanticUndefined:
                property_schema["default"] = value_json(default)
    schema["x-provider-names"] = [spec.name for spec in PROVIDERS]
    return schema


def typescript_types(schema):
    def expression(node):
        if "$ref" in node:
            return node["$ref"].rsplit("/", 1)[1]
        if "anyOf" in node:
            return " | ".join(expression(branch) for branch in node["anyOf"])
        if "const" in node:
            return json.dumps(node["const"])
        if "enum" in node:
            return " | ".join(json.dumps(value) for value in node["enum"])
        kind = node.get("type")
        if kind == "object":
            if "properties" in node:
                fields = [f"  {json.dumps(field.get('x-output', key))}: {expression(field)};"
                          for key, field in node["properties"].items()]
                if node.get("x-extra") == "allow":
                    fields.append("  [key: string]: Json;")
                return "{\n" + "\n".join(fields) + "\n}"
            additional = node.get("additionalProperties")
            return f"Record<string, {expression(additional) if isinstance(additional, dict) else 'Json'}>"
        if kind == "array":
            return f"({expression(node.get('items', {}))})[]"
        return {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}.get(kind, "Json")
    declarations = ["// Generated by scripts/export_ts_config_contract.py; do not edit.",
                    "import type { Json } from './decoder.ts';"]
    for name, node in schema["$defs"].items():
        declarations.append(f"export type {name} = {expression(node)};")
    declarations.append(f"export type ConfigData = {expression(schema)};")
    return "\n\n".join(declarations) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with patch("nanobot.config.schema.detect_system_timezone", return_value="UTC"):
        schema = contract()
        content = json.dumps(schema, ensure_ascii=False, indent=2) + "\n"
        declarations = typescript_types(schema)
    if args.check:
        if (OUTPUT.read_text(encoding="utf-8") != content
                or OUTPUT.with_name("types.ts").read_text(encoding="utf-8") != declarations):
            raise SystemExit("TS config contract is stale; run python -m scripts.export_ts_config_contract")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        OUTPUT.with_name("types.ts").write_text(declarations, encoding="utf-8")


if __name__ == "__main__":
    main()
